"""Share Revo3 visual/collision subtrees without modifying vendored assets.

Run with usd-core or an initialized Isaac Sim Python interpreter:
    python scripts/preprocessing/make_revo3_instanceable.py

The geometry library uses references, not copies of vertex data. Materials whose
bindings cross an instance boundary are referenced inside that boundary. Bodies,
joints and their physical state stay outside the shared subtrees.
"""

from pathlib import Path

from pxr import Sdf, Usd, UsdGeom, UsdPhysics, UsdShade


def generate(source: Path, output: Path) -> int:
    source, output = source.resolve(), output.resolve()
    if source.parent != output.parent or source == output:
        raise ValueError("Write a separate instancing layer next to the source USD")
    stage = Usd.Stage.Open(str(source))
    roots = sorted(
        p.GetPath()
        for p in stage.Traverse()
        if p.GetName() in {"visuals", "collisions"} and p.GetParent().HasAPI(UsdPhysics.RigidBodyAPI)
    )
    meshes = [p for p in stage.Traverse() if p.IsA(UsdGeom.Mesh)]
    if not roots or any(not any(p.GetPath().HasPrefix(root) for root in roots) for p in meshes):
        raise ValueError("Every mesh must belong to a body's visual/collision subtree")

    library_path = output.with_name("revo3_right_geometry.usda")
    library = Sdf.Layer.CreateAnonymous("revo3_geometry.usda")
    layer = Sdf.Layer.CreateAnonymous("revo3_instanceable.usda")
    layer.subLayerPaths = [source.name]
    layer.documentation = (
        "Generated by scripts/preprocessing/make_revo3_instanceable.py; "
        "share geometry only, keeping rigid bodies and joints independent."
    )
    library.documentation = "Generated geometry and material references; contains no independent rigid bodies."
    for item in (layer, library):
        item.defaultPrim = stage.GetDefaultPrim().GetName()
        item.pseudoRoot.SetInfo("metersPerUnit", UsdGeom.GetStageMetersPerUnit(stage))
        item.pseudoRoot.SetInfo("upAxis", UsdGeom.GetStageUpAxis(stage))

    # Author layers directly so relative references resolve at their exported
    # location, without temporarily composing relative to the working directory.
    with Sdf.ChangeBlock():
        for root in roots:
            spec = Sdf.CreatePrimInLayer(library, root)
            spec.referenceList.prependedItems = [Sdf.Reference(source.name, root)]
            for prefix in root.GetPrefixes():
                ancestor = Sdf.CreatePrimInLayer(library, prefix)
                ancestor.specifier = Sdf.SpecifierDef
                ancestor.typeName = "Xform"
            for prim in Usd.PrimRange(stage.GetPrimAtPath(root)):
                if prim.HasAPI(UsdPhysics.RigidBodyAPI) or prim.IsA(UsdPhysics.Joint):
                    raise ValueError(f"Cannot share independent physical state: {prim.GetPath()}")
                for rel in prim.GetRelationships():
                    targets = rel.GetTargets()
                    external = [target for target in targets if not target.HasPrefix(root)]
                    if not external:
                        continue
                    if rel.GetName() != "material:binding" or any(
                        not stage.GetPrimAtPath(target).IsA(UsdShade.Material) for target in external
                    ):
                        raise ValueError(f"Cannot safely relocate relationship: {rel.GetPath()}")
                    remap = {}
                    scope = Sdf.CreatePrimInLayer(library, root.AppendPath("__materials"))
                    scope.specifier = Sdf.SpecifierDef
                    scope.typeName = "Scope"
                    for target in external:
                        destination = root.AppendPath("__materials").AppendChild(target.name)
                        material = Sdf.CreatePrimInLayer(library, destination)
                        material.referenceList.prependedItems = [Sdf.Reference(source.name, target)]
                        remap[target] = destination
                    binding = Sdf.RelationshipSpec(
                        Sdf.CreatePrimInLayer(library, prim.GetPath()), rel.GetName(), custom=False
                    )
                    binding.targetPathList.explicitItems = [remap.get(target, target) for target in targets]
            spec = Sdf.CreatePrimInLayer(layer, root)
            spec.referenceList.prependedItems = [Sdf.Reference(library_path.name, root)]
            spec.instanceable = True
    library.Export(str(library_path))
    layer.Export(str(output))
    return len(roots)


if __name__ == "__main__":
    assets = Path(__file__).resolve().parents[2] / "source/viserdex/viserdex/assets"
    count = generate(assets / "revo3_right_isaaclab.usda", assets / "revo3_right_instanceable.usda")
    print(f"Generated {count} geometry instances")
